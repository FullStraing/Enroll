export function getMessages(locale: Locale) {
  return messages[locale];
}

export function translateAppShellTitle(locale: Locale, value?: string) {
  if (!value) return value;
  const titleMap = messages[locale].shell.titleMap as Record<string, string>;
  return titleMap[value] ?? value;
}

export function translateAppShellSubtitle(locale: Locale, value?: string) {
  if (!value) return value;
  const subtitleMap = messages[locale].shell.subtitleMap as Record<string, string>;
  return subtitleMap[value] ?? value;
}
