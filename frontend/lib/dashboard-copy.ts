export function getDashboardCopy(locale: Locale) {
  return dashboardCopy[locale];
}

export function translateDashboardStatus(locale: Locale, value?: string | null) {
  if (!value) return "";
  const normalized = value.toLowerCase().replaceAll(" ", "_");
  const map = dashboardCopy[locale].statuses as Record<string, string>;
  return map[normalized] ?? value.replaceAll("_", " ");
}
